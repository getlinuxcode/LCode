import Foundation

/// Simulator package generated next to an xtool project: the same sources, built for Linux against
/// LSimUI, which is exposed as the `SwiftUI` module.
public struct SimulatorBuild {
    public let project: XtoolProject
    /// Root of the LCode repository (provides LSimUI, LSimHost and the SwiftUI module).
    public let lcodeRoot: URL
    /// <project>/.lcode/simulator
    public var directory: URL { project.root.appendingPathComponent(".lcode/simulator") }

    public init(project: XtoolProject, lcodeRoot: URL) {
        self.project = project
        self.lcodeRoot = lcodeRoot
    }

    /// Warnings about what the simulator cannot reproduce (yet).
    public var warnings: [String] {
        var w: [String] = []
        for t in project.targets {
            if t.hasResources, Self.otherResources(in: t.path) {
                w.append("Target \(t.name) has resources outside asset catalogs: the simulator only uses images and colors from .xcassets.")
            }
        }
        return w
    }

    /// Whether the Resources folder holds anything besides asset catalogs.
    static func otherResources(in folder: URL) -> Bool {
        let resources = folder.appendingPathComponent("Resources")
        let items = (try? FileManager.default.contentsOfDirectory(atPath: resources.path)) ?? []
        return items.contains { !$0.hasSuffix(".xcassets") && !$0.hasPrefix(".") }
    }

    /// Writes the simulator package (idempotent: only changed files are rewritten).
    public func generate() throws {
        let fm = FileManager.default
        let targetsDir = directory.appendingPathComponent("Targets")
        try fm.createDirectory(at: targetsDir, withIntermediateDirectories: true)

        // Source copy with `#Preview` blocks rewritten as plain functions on the same lines.
        var index = 0
        for t in project.targets {
            let found = try SourceMirror.mirror(from: t.path, to: targetsDir.appendingPathComponent(t.name),
                                                removeMain: false, firstIndex: index)
            index += found.reduce(0) { $0 + $1.previews.count }
        }

        let lcodeName = lcodeRoot.lastPathComponent
        let packages = try PackageOverlay(project: project, lcodeRoot: lcodeRoot).dependencyDeclarations()
        var targets: [String] = []
        for t in project.targets {
            let deps = t.localDependencies.map { "\"\($0)\"" } + t.externalProducts.map(\.declaration)
                + PackageOverlay.lsimModules.map { ".product(name: \"\($0)\", package: \"\(lcodeName)\")" }
            let kind = t.name == project.appTarget ? "executableTarget" : "target"
            targets.append("""
                    .\(kind)(
                        name: "\(t.name)",
                        dependencies: [\(deps.joined(separator: ", "))],
                        path: "Targets/\(t.name)",
                        // Swift 5 mode: LSimUI is not fully concurrency-annotated yet.
                        swiftSettings: [.swiftLanguageMode(.v5)]
                    ),
            """)
        }

        let manifest = """
        // swift-tools-version: 6.0
        // Generated by LCode — do not edit: regenerated on every `lcode run`.
        // Sources mirror the \(project.name) project; `import SwiftUI` resolves to LSimUI.
        import PackageDescription

        let package = Package(
            name: "\(project.name)Simulator",
            dependencies: [
                .package(path: "\(lcodeRoot.path)"),
        \(packages.map { "        " + $0 + "," }.joined(separator: "\n"))
            ],
            targets: [
        \(targets.joined(separator: "\n"))
            ]
        )

        """
        let manifestURL = directory.appendingPathComponent("Package.swift")
        if (try? String(contentsOf: manifestURL, encoding: .utf8)) != manifest {
            try manifest.write(to: manifestURL, atomically: true, encoding: .utf8)
        }
    }

    /// Builds the app for the simulator; returns the executable's path.
    public func build() throws -> URL {
        try generate()
        let status = try Shell.run(["swift", "build", "--package-path", directory.path, "--product", project.appTarget])
        guard status == 0 else {
            throw LCodeError("Simulator build failed (see the errors above).")
        }
        let binPath = try Shell.capture(["swift", "build", "--package-path", directory.path, "--show-bin-path"])
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return URL(fileURLWithPath: binPath).appendingPathComponent(project.appTarget)
    }
}

extension SimulatorBuild {
    /// Maps a mirrored file path back to the original (for compiler errors).
    public func originalPath(for copyPath: String) -> String {
        for t in project.targets {
            let prefix = directory.appendingPathComponent("Targets/\(t.name)").path + "/"
            if copyPath.hasPrefix(prefix) { return t.path.path + "/" + copyPath.dropFirst(prefix.count) }
        }
        return copyPath
    }
}

/// Simulator launch options (LSimHost's LSIM_* variables).
public struct SimulatorOptions {
    public var device = "iphone17promax"
    public var dark = false
    public var screenshot: String?
    public var taps: String?
    /// Seconds of real run time before the screenshot (media, network, async tasks).
    public var wait: Double?

    public init() {}

    var environment: [String: String] {
        var env = ["LSIM_DEVICE": device]
        if dark { env["LSIM_DARK"] = "1" }
        if let screenshot { env["LSIM_SCREENSHOT"] = screenshot }
        if let taps { env["LSIM_TAPS"] = taps }
        if let wait { env["LSIM_WAIT"] = String(wait) }
        return env
    }
}

extension SimulatorBuild {
    /// Builds and runs the app in the simulator (a window, or a screenshot if `screenshot` is set).
    public func run(_ options: SimulatorOptions) throws -> Int32 {
        let binary = try build()
        return try Shell.run([binary.path], environment: options.environment.merging(project.simulatorEnvironment) { a, _ in a })
    }
}
